SUBTRACT = [14, 13, 10, 13, 15, 16, 12, 13, 11, 13, 13]
ASKING = 0

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    context.user_data['answers'] = []
    context.user_data['current'] = 0
    await update.message.reply_text(
        "🧠 Привет! Я проведу тест «Психологические защиты».\n"
        "На каждое утверждение ответь числом от 1 до 5:\n"
        "1 — почти никогда\n2 — редко\n3 — иногда\n4 — часто\n5 — очень часто\n\n"
        "Отвечай честно. Для отмены напиши /cancel."
    )
    return await ask_question(update, context)

async def ask_question(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    idx = context.user_data['current']
    if idx >= 55:
        return await finish(update, context)
    module_idx = idx // 5
    question_idx = idx % 5
    question_text = QUESTIONS[module_idx][question_idx]
    num = idx + 1
    await update.message.reply_text(
        f"📝 Вопрос {num} из 55:\n\n{question_text}\n\nВведите число от 1 до 5:"
    )
    return ASKING

async def handle_answer(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    text = update.message.text.strip()
    if not text.isdigit() or int(text) not in range(1, 6):
        await update.message.reply_text("⚠️ Введите число от 1 до 5. Попробуйте снова:")
        return ASKING
    context.user_data['answers'].append(int(text))
    context.user_data['current'] += 1
    return await ask_question(update, context)

async def finish(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    answers = context.user_data['answers']
    if len(answers) != 55:
        await update.message.reply_text("❌ Ошибка. Начни заново /start.")
        return ConversationHandler.END
    
    module_sums = [sum(answers[i*5:(i+1)*5]) for i in range(11)]
    final_results = [module_sums[i] - SUBTRACT[i] for i in range(11)]
    
    sorted_modules = sorted(range(11), key=lambda i: final_results[i], reverse=True)
    
    lines = ["📊 *Ваши результаты теста «Психологические защиты»*\n"]
    lines.append("Ваши защитные механизмы (по убыванию выраженности):")
    lines.append("")
    
    for i, idx in enumerate(sorted_modules, 1):
        info = DEFENSE_INFO[idx]
        name = info["name"]
        desc = info["desc"]
        result = final_results[idx]
        
        if i <= 3:
            emoji = "🔴"
        elif i <= 6:
            emoji = "🟡"
        else:
            emoji = "🟢"
        
        lines.append(f"{emoji} *{i}. {name}* — {result} баллов")
        lines.append(f"   _{desc}_")
        lines.append("")
    
    lines.append("🔴 *Красным* выделены 3 самых выраженных защитных механизма.")
    lines.append("")
    lines.append("📩 *Отправьте свои результаты мне в ВК!*")
    lines.append("Я дам вам персональные рекомендации по работе с вашими защитами.")
    lines.append("")
    lines.append("👉 *Наше сообщество ВК:* [Все будет, просто нужно время](https://vk.ru/club240718452)")
    lines.append("✍️ Напишите нам туда, и мы поможем вам!")
    
    await update.message.reply_text("\n".join(lines), parse_mode="Markdown")
    context.user_data.clear()
    return ConversationHandler.END

async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    context.user_data.clear()
    await update.message.reply_text("❌ Тест отменён. /start чтобы начать заново.")
    return ConversationHandler.END

def main():
    app = Application.builder().token(TOKEN).build()
    conv = ConversationHandler(
        entry_points=[CommandHandler('start', start)],
        states={ASKING: [MessageHandler(filters.TEXT & ~filters.COMMAND, handle_answer)]},
        fallbacks=[CommandHandler('cancel', cancel)],
    )
    app.add_handler(conv)
    print("✅ Бот запущен!")
    
    # --- ЭТО ВАЖНОЕ ИСПРАВЛЕНИЕ! ---
