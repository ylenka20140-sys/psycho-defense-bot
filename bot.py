def find_test_by_trigger(text):
    """Находит тест по триггеру"""
    text = text.lower().strip()
    for test_id, test_data in TESTS.items():
        for trigger in test_data["triggers"]:
            if text == trigger or text.startswith(trigger):
                return test_id
    return None

